class DependencyManager:
    """
    Dependency installation is restricted.

    Runtime may only install packages declared in the project's
    requirements file, not arbitrary model-generated package names.
    """

    REQUIREMENTS_FILE = (
        PROJECT_ROOT / "requirements.txt"
    )

    PACKAGE_RE = re.compile(
        r"^[A-Za-z0-9_.-]+"
        r"(?:\[[A-Za-z0-9_,.-]+\])?"
        r"(?:==|>=|<=|~=|>|<)?"
        r"[A-Za-z0-9_.+-]*$"
    )

    def __init__(
        self,
        runner: CommandRunner,
        db: RuntimeDatabase,
    ):
        self.runner = runner
        self.db = db

    def declared_packages(self) -> List[str]:
        if not self.REQUIREMENTS_FILE.exists():
            return []

        packages: List[str] = []

        for raw in self.REQUIREMENTS_FILE.read_text(
            encoding="utf-8"
        ).splitlines():
            line = raw.strip()

            if not line or line.startswith("#"):
                continue

            if (
                line.startswith("-")
                or "://" in line
                or line.startswith("git+")
            ):
                self.db.event(
                    "DEPENDENCY_BLOCKED",
                    Risk.HIGH,
                    {"entry": line},
                )
                continue

            if not self.PACKAGE_RE.fullmatch(
                line
            ):
                self.db.event(
                    "DEPENDENCY_BLOCKED",
                    Risk.HIGH,
                    {"entry": line},
                )
                continue

            packages.append(line)

        return packages

    def install_declared(
        self,
    ) -> CommandResult:
        packages = self.declared_packages()

        if not packages:
            return CommandResult(
                success=True,
                argv=[],
                returncode=0,
                stdout="No declared dependencies.",
            )

        if not AUTO_INSTALL_DEPENDENCIES:
            return CommandResult(
                success=False,
                argv=[],
                returncode=None,
                stderr=(
                    "Automatic dependency installation "
                    "is disabled."
                ),
            )

        argv = [
            sys.executable,
            "-m",
            "pip",
            "install",
            "--disable-pip-version-check",
            "--no-input",
            *packages,
        ]

        result = self.runner.run(
            argv,
            cwd=PROJECT_ROOT,
            timeout=max(
                COMMAND_TIMEOUT,
                600,
            ),
        )

        self.db.event(
            "DEPENDENCY_INSTALL",
            (
                Risk.MEDIUM
                if result.success
                else Risk.HIGH
            ),
            {
                "success": result.success,
                "packages": packages,
                "returncode": (
                    result.returncode
                ),
            },
        )

        return result


