class MajdAutonomousRuntime:
    def __init__(self):
        self.db = RuntimeDatabase(
            RUNTIME_DB
        )

        self.runner = CommandRunner()

        self.core_loader = CoreLoader(
            CORE_PATH
        )

        self.core = (
            self.core_loader.load()
        )

        self.initial_constitution = (
            self.core_loader
            .constitution_fingerprint()
        )

        self.backups = BackupManager(
            self.db
        )

        self.validator = (
            ProjectValidator(
                self.runner
            )
        )

        self.dependencies = (
            DependencyManager(
                self.runner,
                self.db,
            )
        )

        self.gateway = (
            DevelopmentGateway()
        )

        self.changes = ChangeManager(
            self.db,
            self.backups,
            self.validator,
        )

        self.developer = (
            AutonomousDeveloper(
                self.db,
                self.gateway,
                self.changes,
                self.validator,
                self.core_loader,
            )
        )

        self.git = GitManager(
            self.runner,
            self.db,
        )

        self.deployer = (
            DeploymentManager(
                self.runner,
                self.db,
            )
        )

        self.health_engine = (
            HealthEngine(
                self.validator,
                self.core_loader,
                self.db,
            )
        )

        self.maintenance = (
            MaintenanceEngine(
                self.db,
                self.health_engine,
                self.dependencies,
                self.developer,
                self.git,
                self.deployer,
                self.core_loader,
            )
        )

        self._write_manifest()

    def _assert_constitution(
        self,
    ) -> None:
        current = (
            self.core_loader
            .constitution_fingerprint()
        )

        if (
            current
            != self.initial_constitution
        ):
            self.db.event(
                "CONSTITUTION_CHANGED",
                Risk.CRITICAL,
                {
                    "expected": (
                        self.initial_constitution
                    ),
                    "actual": current,
                },
            )

            raise RuntimeError(
                "Sovereign constitution "
                "changed during runtime"
            )

    def _write_manifest(self) -> None:
        manifest = (
            ProjectManifest.build(
                self.core_loader
            )
        )

        write_json(
            MANIFEST_PATH,
            manifest,
        )

    def bootstrap(self) -> Dict[str, Any]:
        logger.info(
            "Bootstrapping %s %s",
            RUNTIME_NAME,
            RUNTIME_VERSION,
        )

        self._assert_constitution()

        self_check = (
            self.core_loader
            .self_check()
        )

        if not self_check.get("ok"):
            raise RuntimeError(
                "CORE-01 self-check failed"
            )

        validation = (
            self.validator
            .full_validation()
        )

        self._write_manifest()

        result = {
            "ok": validation.success,
            "runtime": RUNTIME_NAME,
            "runtime_version": (
                RUNTIME_VERSION
            ),
            "core_file": CORE_FILENAME,
            "core_self_check": (
                self_check
            ),
            "validation": {
                "success": (
                    validation.success
                ),
                "checks": (
                    validation.checks
                ),
                "errors": (
                    validation.errors
                ),
                "warnings": (
                    validation.warnings
                ),
            },
            "autonomous": True,
            "development_gateway": (
                self.gateway.healthy()
            ),
            "auto_dependencies": (
                AUTO_INSTALL_DEPENDENCIES
            ),
            "auto_git_commit": (
                AUTO_GIT_COMMIT
            ),
            "auto_deploy": (
                AUTO_DEPLOY
            ),
            "time": utc_now(),
        }

        self.db.event(
            "RUNTIME_BOOTSTRAP",
            (
                Risk.LOW
                if result["ok"]
                else Risk.HIGH
            ),
            result,
        )

        return result

    def health(self) -> Dict[str, Any]:
        self._assert_constitution()

        return (
            self.health_engine.check()
        )

    def develop(
        self,
        objective: str,
    ) -> Dict[str, Any]:
        self._assert_constitution()

        result = (
            self.developer.develop(
                objective
            )
        )

        self._assert_constitution()
        self._write_manifest()

        return {
            "ok": result.success,
            "checks": result.checks,
            "errors": result.errors,
            "warnings": result.warnings,
            "time": utc_now(),
        }

    def maintenance_once(
        self,
    ) -> Dict[str, Any]:
        self._assert_constitution()

        result = (
            self.maintenance
            .maintenance_cycle()
        )

        self._assert_constitution()
        self._write_manifest()

        return result

    def run_forever(self) -> int:
        bootstrap = self.bootstrap()

        if not bootstrap["ok"]:
            logger.warning(
                "Initial validation failed; "
                "runtime will attempt maintenance."
            )

        logger.info(
            "Autonomous runtime active. "
            "heartbeat=%ss maintenance=%ss",
            HEARTBEAT_SECONDS,
            MAINTENANCE_SECONDS,
        )

        last_maintenance = 0.0

        while not STOP_EVENT.is_set():
            try:
                self._assert_constitution()

                now = time.monotonic()

                if (
                    now - last_maintenance
                    >= MAINTENANCE_SECONDS
                ):
                    result = (
                        self.maintenance_once()
                    )

                    logger.info(
                        "Maintenance cycle: ok=%s",
                        result["ok"],
                    )

                    last_maintenance = now

                else:
                    health = self.health()

                    logger.info(
                        "Heartbeat: ok=%s",
                        health["ok"],
                    )

                STOP_EVENT.wait(
                    HEARTBEAT_SECONDS
                )

            except KeyboardInterrupt:
                STOP_EVENT.set()

            except Exception as exc:
                logger.error(
                    "Runtime cycle failure: %s\n%s",
                    SecretGuard.redact(
                        str(exc)
                    ),
                    SecretGuard.redact(
                        traceback.format_exc()
                    ),
                )

                self.db.event(
                    "RUNTIME_CYCLE_FAILURE",
                    Risk.HIGH,
                    {
                        "error": (
                            f"{type(exc).__name__}: "
                            f"{exc}"
                        )
                    },
                )

                STOP_EVENT.wait(
                    HEARTBEAT_SECONDS
                )

        logger.info(
            "Autonomous runtime stopped."
        )

        return 0


