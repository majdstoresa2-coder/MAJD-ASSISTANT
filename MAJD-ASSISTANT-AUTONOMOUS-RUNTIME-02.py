def handle_stop_signal(
    signum: int,
    frame: Any,
) -> None:
    del frame

    logger.info(
        "Stop signal received: %s",
        signum,
    )

    STOP_EVENT.set()


def install_signal_handlers() -> None:
    for sig in (
        signal.SIGINT,
        signal.SIGTERM,
    ):
        with contextlib.suppress(
            Exception
        ):
            signal.signal(
                sig,
                handle_stop_signal,
            )


