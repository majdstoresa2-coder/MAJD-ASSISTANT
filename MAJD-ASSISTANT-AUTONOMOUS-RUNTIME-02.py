SECRET_PATTERNS: Tuple[re.Pattern[str], ...] = (
    re.compile(
        r"(?i)\b("
        r"api[_-]?key|secret|token|password|passwd|"
        r"authorization"
        r")\s*[:=]\s*['\"]?([^\s'\";,]+)"
    ),
    re.compile(
        r"\bgh[pousr]_[A-Za-z0-9_]{20,}\b"
    ),
    re.compile(
        r"\bgithub_pat_[A-Za-z0-9_]{20,}\b"
    ),
    re.compile(
        r"\bsk-[A-Za-z0-9_-]{16,}\b"
    ),
    re.compile(
        r"-----BEGIN "
        r"(?:RSA |EC |OPENSSH )?"
        r"PRIVATE KEY-----[\s\S]*?"
        r"-----END "
        r"(?:RSA |EC |OPENSSH )?"
        r"PRIVATE KEY-----"
    ),
)


class SecretGuard:
    @staticmethod
    def redact(value: str) -> str:
        output = value or ""

        for pattern in SECRET_PATTERNS:
            if pattern.groups >= 2:
                output = pattern.sub(
                    lambda match: (
                        f"{match.group(1)}=[REDACTED]"
                    ),
                    output,
                )
            else:
                output = pattern.sub(
                    "[REDACTED_SECRET]",
                    output,
                )

        return output

    @staticmethod
    def contains_secret(value: str) -> bool:
        return any(
            pattern.search(value or "")
            for pattern in SECRET_PATTERNS
        )


