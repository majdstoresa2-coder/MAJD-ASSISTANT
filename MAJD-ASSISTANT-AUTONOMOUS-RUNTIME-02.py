class ProjectManifest:
    @staticmethod
    def build(
        core_loader: CoreLoader,
    ) -> Dict[str, Any]:
        files: List[Dict[str, Any]] = []

        for path in PROJECT_ROOT.rglob("*"):
            if not path.is_file():
                continue

            if ".git" in path.parts:
                continue

            if "__pycache__" in path.parts:
                continue

            if ".majd-runtime" in path.parts:
                continue

            try:
                size = path.stat().st_size
            except OSError:
                continue

            files.append(
                {
                    "path": relative_path(
                        path
                    ),
                    "size": size,
                    "sha256": (
                        sha256_file(path)
                        if size <= 5_000_000
                        else None
                    ),
                }
            )

        return {
            "project": "MAJD-ASSISTANT",
            "public_name": APP_NAME,
            "runtime_version": (
                RUNTIME_VERSION
            ),
            "generated_at": utc_now(),
            "project_root": str(
                PROJECT_ROOT
            ),
            "core": {
                "file": CORE_FILENAME,
                "exists": CORE_PATH.exists(),
                "sha256": (
                    sha256_file(CORE_PATH)
                    if CORE_PATH.exists()
                    else None
                ),
                "constitution_fingerprint": (
                    core_loader
                    .constitution_fingerprint()
                ),
            },
            "runtime": {
                "file": RUNTIME_FILENAME,
                "sha256": (
                    sha256_file(
                        RUNTIME_PATH
                    )
                    if RUNTIME_PATH.exists()
                    else None
                ),
            },
            "files": files,
        }


