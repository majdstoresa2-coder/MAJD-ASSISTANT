class RuntimeDatabase:
    def __init__(self, path: Path):
        self.path = path
        self._lock = threading.RLock()
        self.initialize()

    def connect(self) -> sqlite3.Connection:
        connection = sqlite3.connect(
            self.path,
            timeout=30,
            isolation_level=None,
            check_same_thread=False,
        )

        connection.row_factory = sqlite3.Row
        connection.execute(
            "PRAGMA journal_mode=WAL"
        )
        connection.execute(
            "PRAGMA foreign_keys=ON"
        )
        connection.execute(
            "PRAGMA busy_timeout=30000"
        )

        return connection

    def initialize(self) -> None:
        with self._lock, self.connect() as db:
            db.executescript(
                """
                CREATE TABLE IF NOT EXISTS runtime_events (
                    id TEXT PRIMARY KEY,
                    event_type TEXT NOT NULL,
                    risk TEXT NOT NULL,
                    details TEXT NOT NULL,
                    created_at TEXT NOT NULL
                );

                CREATE TABLE IF NOT EXISTS jobs (
                    id TEXT PRIMARY KEY,
                    job_type TEXT NOT NULL,
                    status TEXT NOT NULL,
                    details TEXT NOT NULL,
                    created_at TEXT NOT NULL,
                    updated_at TEXT NOT NULL
                );

                CREATE TABLE IF NOT EXISTS backups (
                    id TEXT PRIMARY KEY,
                    source_path TEXT NOT NULL,
                    backup_path TEXT NOT NULL,
                    sha256 TEXT NOT NULL,
                    created_at TEXT NOT NULL
                );

                CREATE TABLE IF NOT EXISTS component_versions (
                    component TEXT PRIMARY KEY,
                    version TEXT NOT NULL,
                    source TEXT,
                    metadata TEXT NOT NULL DEFAULT '{}',
                    updated_at TEXT NOT NULL
                );

                CREATE TABLE IF NOT EXISTS generated_files (
                    path TEXT PRIMARY KEY,
                    sha256 TEXT NOT NULL,
                    source TEXT NOT NULL,
                    status TEXT NOT NULL,
                    metadata TEXT NOT NULL DEFAULT '{}',
                    updated_at TEXT NOT NULL
                );
                """
            )

    def event(
        self,
        event_type: str,
        risk: Risk,
        details: Mapping[str, Any],
    ) -> None:
        protected = SecretGuard.redact(
            safe_json(dict(details))
        )

        with self._lock, self.connect() as db:
            db.execute(
                """
                INSERT INTO runtime_events
                (id,event_type,risk,details,created_at)
                VALUES (?,?,?,?,?)
                """,
                (
                    new_id("event"),
                    event_type,
                    risk.value,
                    protected,
                    utc_now(),
                ),
            )

    def create_job(
        self,
        job_type: str,
        details: Mapping[str, Any],
    ) -> str:
        job_id = new_id("job")
        now = utc_now()

        with self._lock, self.connect() as db:
            db.execute(
                """
                INSERT INTO jobs
                (id,job_type,status,details,created_at,updated_at)
                VALUES (?,?,?,?,?,?)
                """,
                (
                    job_id,
                    job_type,
                    JobStatus.PENDING.value,
                    SecretGuard.redact(
                        safe_json(dict(details))
                    ),
                    now,
                    now,
                ),
            )

        return job_id

    def update_job(
        self,
        job_id: str,
        status: JobStatus,
        details: Mapping[str, Any],
    ) -> None:
        with self._lock, self.connect() as db:
            db.execute(
                """
                UPDATE jobs
                SET status = ?,
                    details = ?,
                    updated_at = ?
                WHERE id = ?
                """,
                (
                    status.value,
                    SecretGuard.redact(
                        safe_json(dict(details))
                    ),
                    utc_now(),
                    job_id,
                ),
            )

    def save_backup(
        self,
        record: BackupRecord,
    ) -> None:
        with self._lock, self.connect() as db:
            db.execute(
                """
                INSERT INTO backups
                (id,source_path,backup_path,sha256,created_at)
                VALUES (?,?,?,?,?)
                """,
                (
                    record.backup_id,
                    record.source_path,
                    record.backup_path,
                    record.sha256,
                    record.created_at,
                ),
            )

    def record_generated_file(
        self,
        path: Path,
        source: str,
        status: str,
        metadata: Mapping[str, Any],
    ) -> None:
        digest = (
            sha256_file(path)
            if path.exists()
            else ""
        )

        with self._lock, self.connect() as db:
            db.execute(
                """
                INSERT INTO generated_files
                (path,sha256,source,status,metadata,updated_at)
                VALUES (?,?,?,?,?,?)
                ON CONFLICT(path) DO UPDATE SET
                    sha256=excluded.sha256,
                    source=excluded.source,
                    status=excluded.status,
                    metadata=excluded.metadata,
                    updated_at=excluded.updated_at
                """,
                (
                    relative_path(path),
                    digest,
                    source,
                    status,
                    SecretGuard.redact(
                        safe_json(dict(metadata))
                    ),
                    utc_now(),
                ),
            )


