# ============================================================

class ProviderUpdatePolicy:
    MIN_SECURITY = 0.95
    MIN_QUALITY = 0.85
    MIN_COMPATIBILITY = 0.90

    @classmethod
    def approve(
        cls,
        candidate: ProviderCandidate,
    ) -> Tuple[bool, str]:
        if not candidate.tests_passed:
            return False, "TESTS_FAILED"

        if not candidate.sandbox_verified:
            return False, "SANDBOX_NOT_VERIFIED"

        if (
            candidate.security_score
            < cls.MIN_SECURITY
        ):
            return False, "SECURITY_TOO_LOW"

        if (
            candidate.quality_score
            < cls.MIN_QUALITY
        ):
            return False, "QUALITY_TOO_LOW"

        if (
            candidate.compatibility_score
            < cls.MIN_COMPATIBILITY
        ):
            return (
                False,
                "COMPATIBILITY_TOO_LOW",
            )

        return True, "APPROVED"


