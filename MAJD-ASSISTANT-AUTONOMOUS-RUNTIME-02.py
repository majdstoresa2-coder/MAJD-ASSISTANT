class CoreLoader:
    def __init__(self, path: Path):
        self.path = path
        self.module: Optional[Any] = None

    def validate_exists(self) -> None:
        if not self.path.exists():
            raise FileNotFoundError(
                f"Required core missing: {self.path}"
            )

    def load(self) -> Any:
        self.validate_exists()

        module_name = (
            "majd_assistant_core_01"
        )

        spec = importlib.util.spec_from_file_location(
            module_name,
            self.path,
        )

        if spec is None or spec.loader is None:
            raise RuntimeError(
                "Unable to create CORE-01 module spec"
            )

        module = importlib.util.module_from_spec(
            spec
        )

        sys.modules[module_name] = module
        spec.loader.exec_module(module)

        self.module = module
        return module

    def constitution_fingerprint(self) -> str:
        module = self.module or self.load()

        constitution = getattr(
            module,
            "SOVEREIGN_CONSTITUTION",
            None,
        )

        if not constitution:
            raise RuntimeError(
                "CORE-01 sovereign constitution missing"
            )

        return sha256_bytes(
            safe_json(list(constitution)).encode(
                "utf-8"
            )
        )

    def self_check(self) -> Dict[str, Any]:
        module = self.module or self.load()

        function = getattr(
            module,
            "startup_self_check",
            None,
        )

        if not callable(function):
            raise RuntimeError(
                "CORE-01 startup_self_check missing"
            )

        result = function()

        if not isinstance(result, dict):
            raise RuntimeError(
                "Invalid CORE-01 self-check result"
            )

        return result


