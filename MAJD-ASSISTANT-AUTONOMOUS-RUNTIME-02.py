class DevelopmentGateway:
    """
    Talks to a MAJD-compatible development gateway.

    Environment:
        MAJD_DEVELOPMENT_GATEWAY_URL
        MAJD_DEVELOPMENT_GATEWAY_TOKEN

    Expected:
        GET  /health
        POST /v1/develop

    The gateway proposes source code.
    This runtime does not blindly trust it.
    """

    def __init__(self):
        self.base_url = os.environ.get(
            "MAJD_DEVELOPMENT_GATEWAY_URL",
            "",
        ).rstrip("/")

        self.token = os.environ.get(
            "MAJD_DEVELOPMENT_GATEWAY_TOKEN",
            "",
        )

    @property
    def configured(self) -> bool:
        return bool(self.base_url)

    def _headers(self) -> Dict[str, str]:
        headers = {
            "Content-Type": "application/json",
            "User-Agent": (
                f"MAJD-Autonomous-Runtime/"
                f"{RUNTIME_VERSION}"
            ),
        }

        if self.token:
            headers["Authorization"] = (
                f"Bearer {self.token}"
            )

        return headers

    def _json_request(
        self,
        method: str,
        endpoint: str,
        payload: Optional[
            Dict[str, Any]
        ] = None,
    ) -> Dict[str, Any]:
        url = (
            f"{self.base_url}"
            f"{endpoint}"
        )

        data = (
            safe_json(payload).encode(
                "utf-8"
            )
            if payload is not None
            else None
        )

        request = urllib.request.Request(
            url=url,
            data=data,
            headers=self._headers(),
            method=method,
        )

        with urllib.request.urlopen(
            request,
            timeout=60,
        ) as response:
            raw = response.read(
                MAX_GENERATED_FILE_BYTES
                + 500000
            )

        if (
            len(raw)
            > MAX_GENERATED_FILE_BYTES
            + 500000
        ):
            raise ValueError(
                "Development response too large"
            )

        return json.loads(
            raw.decode("utf-8")
        )

    def healthy(self) -> bool:
        if not self.configured:
            return False

        try:
            result = self._json_request(
                "GET",
                "/health",
            )
            return bool(
                result.get("ok")
            )
        except Exception:
            return False

    def propose(
        self,
        objective: str,
        project_manifest: Mapping[
            str,
            Any,
        ],
        errors: Sequence[str],
        allowed_root: str = "majd_generated",
    ) -> Optional[ChangeProposal]:
        if not self.healthy():
            return None

        response = self._json_request(
            "POST",
            "/v1/develop",
            {
                "objective": objective,
                "project_manifest": (
                    dict(project_manifest)
                ),
                "errors": list(errors),
                "constraints": {
                    "allowed_root": (
                        allowed_root
                    ),
                    "no_secrets": True,
                    "no_shell_strings": True,
                    "no_security_bypass": True,
                    "complete_files_only": True,
                    "production_quality": True,
                },
            },
        )

        if not response.get("success"):
            return None

        relative = str(
            response.get(
                "relative_path",
                "",
            )
        ).strip()

        content = response.get(
            "content"
        )

        if not relative or not isinstance(
            content,
            str,
        ):
            return None

        return ChangeProposal(
            proposal_id=new_id("proposal"),
            change_type=ChangeType.CREATE,
            relative_path=relative,
            content=content,
            reason=str(
                response.get(
                    "reason",
                    objective,
                )
            ),
            source=str(
                response.get(
                    "provider",
                    "development-gateway",
                )
            ),
        )


