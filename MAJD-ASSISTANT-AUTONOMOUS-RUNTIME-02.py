class HealthEngine:
    def __init__(
        self,
        validator: ProjectValidator,
        core_loader: CoreLoader,
        db: RuntimeDatabase,
    ):
        self.validator = validator
        self.core_loader = core_loader
        self.db = db

    def check(self) -> Dict[str, Any]:
        started = time.monotonic()

        validation = (
            self.validator.full_validation()
        )

        capabilities = (
            CapabilityDiscovery.discover()
        )

        result = {
            "ok": validation.success,
            "time": utc_now(),
            "runtime": {
                "name": RUNTIME_NAME,
                "version": (
                    RUNTIME_VERSION
                ),
            },
            "core": {
                "exists": CORE_PATH.exists(),
                "constitution_fingerprint": (
                    self.core_loader
                    .constitution_fingerprint()
                ),
            },
            "validation": {
                "success": (
                    validation.success
                ),
                "checks": (
                    validation.checks
                ),
                "errors": (
                    validation.errors
                ),
                "warnings": (
                    validation.warnings
                ),
            },
            "capabilities": capabilities,
            "duration_ms": int(
                (
                    time.monotonic()
                    - started
                )
                * 1000
            ),
        }

        write_json(
            HEALTH_PATH,
            result,
        )

        write_json(
            CAPABILITY_PATH,
            capabilities,
        )

        self.db.event(
            "HEALTH_CHECK",
            (
                Risk.LOW
                if result["ok"]
                else Risk.HIGH
            ),
            {
                "ok": result["ok"],
                "duration_ms": (
                    result["duration_ms"]
                ),
                "errors": (
                    validation.errors
                ),
            },
        )

        return result


