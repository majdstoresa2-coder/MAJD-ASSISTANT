class ProtectedPathPolicy:
    ABSOLUTELY_PROTECTED = {
        ".git",
        ".github",
        ".ssh",
    }

    PROTECTED_FILES = {
        CORE_FILENAME,
        RUNTIME_FILENAME,
    }

    SECRET_FILE_NAMES = {
        ".env",
        ".env.local",
        ".env.production",
        "credentials.json",
        "secrets.json",
        "id_rsa",
        "id_ed25519",
    }

    @classmethod
    def safe_target(
        cls,
        relative: str,
        allow_core_update: bool = False,
    ) -> Tuple[bool, str]:
        candidate = Path(relative)

        if candidate.is_absolute():
            return False, "ABSOLUTE_PATH_BLOCKED"

        if ".." in candidate.parts:
            return False, "PATH_TRAVERSAL_BLOCKED"

        if not candidate.parts:
            return False, "EMPTY_PATH"

        if candidate.parts[0] in cls.ABSOLUTELY_PROTECTED:
            return False, "PROTECTED_DIRECTORY"

        if candidate.name in cls.SECRET_FILE_NAMES:
            return False, "SECRET_FILE_BLOCKED"

        if candidate.name == RUNTIME_FILENAME:
            return False, "RUNTIME_SELF_MODIFICATION_BLOCKED"

        if (
            candidate.name == CORE_FILENAME
            and not allow_core_update
        ):
            return False, "CORE_UPDATE_BLOCKED"

        return True, "ALLOWED"


