class ProjectValidator:
    def __init__(
        self,
        runner: CommandRunner,
    ):
        self.runner = runner

    def compile_file(
        self,
        path: Path,
    ) -> ValidationResult:
        result = self.runner.run(
            [
                sys.executable,
                "-m",
                "py_compile",
                str(path),
            ],
            cwd=PROJECT_ROOT,
        )

        return ValidationResult(
            success=result.success,
            checks={
                "py_compile": result.success,
                "returncode": result.returncode,
            },
            errors=(
                []
                if result.success
                else [result.stderr or result.stdout]
            ),
        )

    def compile_project(
        self,
    ) -> ValidationResult:
        python_files = [
            path
            for path in PROJECT_ROOT.rglob("*.py")
            if ".git" not in path.parts
            and "__pycache__" not in path.parts
            and ".majd-runtime" not in path.parts
        ]

        errors: List[str] = []
        compiled = 0

        for path in python_files:
            result = self.compile_file(path)

            if result.success:
                compiled += 1
            else:
                errors.extend(
                    [
                        f"{relative_path(path)}: {error}"
                        for error in result.errors
                    ]
                )

        return ValidationResult(
            success=not errors,
            checks={
                "python_files": len(
                    python_files
                ),
                "compiled": compiled,
            },
            errors=errors,
        )

    def run_core_self_check(
        self,
    ) -> ValidationResult:
        result = self.runner.run(
            [
                sys.executable,
                str(CORE_PATH),
                "--self-check",
            ],
            cwd=PROJECT_ROOT,
        )

        checks: Dict[str, Any] = {
            "command_success": result.success,
        }

        if result.success:
            try:
                payload = json.loads(
                    result.stdout
                )
                checks["core"] = payload

                return ValidationResult(
                    success=bool(
                        payload.get("ok")
                    ),
                    checks=checks,
                    errors=(
                        []
                        if payload.get("ok")
                        else [
                            "CORE_SELF_CHECK_FAILED"
                        ]
                    ),
                )
            except Exception:
                pass

        return ValidationResult(
            success=False,
            checks=checks,
            errors=[
                result.stderr
                or result.stdout
                or "CORE_SELF_CHECK_FAILED"
            ],
        )

    def run_tests(
        self,
    ) -> ValidationResult:
        test_files = list(
            TEST_DIR.glob("test_*.py")
        )

        if not test_files:
            return ValidationResult(
                success=True,
                checks={
                    "tests_present": False,
                    "tests_run": 0,
                },
                warnings=[
                    "NO_TEST_FILES_PRESENT"
                ],
            )

        result = self.runner.run(
            [
                sys.executable,
                "-m",
                "unittest",
                "discover",
                "-s",
                str(TEST_DIR),
                "-p",
                "test_*.py",
            ],
            cwd=PROJECT_ROOT,
            timeout=COMMAND_TIMEOUT,
        )

        return ValidationResult(
            success=result.success,
            checks={
                "tests_present": True,
                "command_success": (
                    result.success
                ),
            },
            errors=(
                []
                if result.success
                else [
                    result.stderr
                    or result.stdout
                ]
            ),
        )

    def full_validation(
        self,
    ) -> ValidationResult:
        compile_result = (
            self.compile_project()
        )

        core_result = (
            self.run_core_self_check()
        )

        tests_result = self.run_tests()

        success = (
            compile_result.success
            and core_result.success
            and tests_result.success
        )

        return ValidationResult(
            success=success,
            checks={
                "compile": (
                    compile_result.checks
                ),
                "core": core_result.checks,
                "tests": tests_result.checks,
            },
            errors=(
                compile_result.errors
                + core_result.errors
                + tests_result.errors
            ),
            warnings=(
                compile_result.warnings
                + core_result.warnings
                + tests_result.warnings
            ),
        )


