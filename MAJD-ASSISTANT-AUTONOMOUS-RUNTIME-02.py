class DeploymentManager:
    """
    Deployment uses fixed configured hooks.

    No AI-generated shell command is executed.

    Supported environment variables:
        MAJD_DEPLOY_EXECUTABLE
        MAJD_DEPLOY_ARG_1
        ...
        MAJD_DEPLOY_ARG_20

        MAJD_HEALTH_URL
    """

    def __init__(
        self,
        runner: CommandRunner,
        db: RuntimeDatabase,
    ):
        self.runner = runner
        self.db = db

    def deployment_argv(
        self,
    ) -> List[str]:
        executable = os.environ.get(
            "MAJD_DEPLOY_EXECUTABLE",
            "",
        ).strip()

        if not executable:
            return []

        argv = [executable]

        for index in range(1, 21):
            value = os.environ.get(
                f"MAJD_DEPLOY_ARG_{index}"
            )

            if value is None:
                continue

            argv.append(value)

        return argv

    def deploy(self) -> CommandResult:
        if not AUTO_DEPLOY:
            return CommandResult(
                success=False,
                argv=[],
                returncode=None,
                stderr="AUTO_DEPLOY_DISABLED",
            )

        argv = self.deployment_argv()

        if not argv:
            return CommandResult(
                success=False,
                argv=[],
                returncode=None,
                stderr=(
                    "DEPLOYMENT_HOOK_NOT_CONFIGURED"
                ),
            )

        result = self.runner.run(
            argv,
            cwd=PROJECT_ROOT,
            timeout=max(
                COMMAND_TIMEOUT,
                600,
            ),
        )

        self.db.event(
            "DEPLOYMENT_EXECUTED",
            (
                Risk.MEDIUM
                if result.success
                else Risk.HIGH
            ),
            {
                "success": result.success,
                "returncode": (
                    result.returncode
                ),
            },
        )

        return result

    def health_check(self) -> bool:
        url = os.environ.get(
            "MAJD_HEALTH_URL",
            "",
        ).strip()

        if not url:
            return False

        try:
            request = urllib.request.Request(
                url=url,
                method="GET",
                headers={
                    "User-Agent": (
                        f"MAJD-Runtime/"
                        f"{RUNTIME_VERSION}"
                    )
                },
            )

            with urllib.request.urlopen(
                request,
                timeout=20,
            ) as response:
                status = int(
                    getattr(
                        response,
                        "status",
                        0,
                    )
                )

                body = response.read(
                    100000
                )

            if status < 200 or status >= 300:
                return False

            with contextlib.suppress(
                Exception
            ):
                payload = json.loads(
                    body.decode("utf-8")
                )

                if "ok" in payload:
                    return bool(
                        payload["ok"]
                    )

            return True

        except Exception:
            return False


