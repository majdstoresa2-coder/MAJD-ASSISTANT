class SourceValidator:
    FORBIDDEN_PYTHON_CALLS = {
        "eval",
        "exec",
        "compile",
    }

    DANGEROUS_IMPORTS = {
        "pty",
    }

    @classmethod
    def validate_python_source(
        cls,
        content: str,
    ) -> ValidationResult:
        checks: Dict[str, Any] = {}
        errors: List[str] = []
        warnings: List[str] = []

        if len(
            content.encode("utf-8")
        ) > MAX_GENERATED_FILE_BYTES:
            errors.append(
                "GENERATED_FILE_TOO_LARGE"
            )

        if SecretGuard.contains_secret(content):
            errors.append(
                "POSSIBLE_SECRET_IN_SOURCE"
            )

        try:
            tree = ast.parse(content)
            checks["ast_parse"] = True
        except SyntaxError as exc:
            checks["ast_parse"] = False
            errors.append(
                f"SYNTAX_ERROR:{exc.lineno}:{exc.msg}"
            )
            return ValidationResult(
                success=False,
                checks=checks,
                errors=errors,
                warnings=warnings,
            )

        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                if isinstance(node.func, ast.Name):
                    if (
                        node.func.id
                        in cls.FORBIDDEN_PYTHON_CALLS
                    ):
                        warnings.append(
                            f"REVIEW_CALL:{node.func.id}"
                        )

            if isinstance(node, ast.Import):
                for alias in node.names:
                    if (
                        alias.name.split(".")[0]
                        in cls.DANGEROUS_IMPORTS
                    ):
                        warnings.append(
                            f"REVIEW_IMPORT:{alias.name}"
                        )

            if isinstance(
                node,
                ast.ImportFrom,
            ):
                if (
                    node.module
                    and node.module.split(".")[0]
                    in cls.DANGEROUS_IMPORTS
                ):
                    warnings.append(
                        f"REVIEW_IMPORT:{node.module}"
                    )

        checks["secret_scan"] = (
            "POSSIBLE_SECRET_IN_SOURCE"
            not in errors
        )

        return ValidationResult(
            success=not errors,
            checks=checks,
            errors=errors,
            warnings=warnings,
        )


