def runtime_self_check() -> Dict[str, Any]:
    checks: Dict[str, Any] = {
        "runtime_file": (
            RUNTIME_PATH.exists()
        ),
        "core_file": CORE_PATH.exists(),
        "directories": all(
            directory.exists()
            for directory in (
                DATA_DIR,
                LOG_DIR,
                STATE_DIR,
                BACKUP_DIR,
                STAGING_DIR,
                GENERATED_DIR,
                TEST_DIR,
            )
        ),
        "secret_redaction": False,
        "database": False,
        "core_import": False,
        "constitution": False,
    }

    test_secret = (
        "api_key=THIS_VALUE_MUST_HIDE"
    )

    checks["secret_redaction"] = (
        "THIS_VALUE_MUST_HIDE"
        not in SecretGuard.redact(
            test_secret
        )
    )

    try:
        db = RuntimeDatabase(
            RUNTIME_DB
        )

        with db.connect() as connection:
            connection.execute(
                "SELECT 1"
            ).fetchone()

        checks["database"] = True

    except Exception:
        checks["database"] = False

    try:
        loader = CoreLoader(
            CORE_PATH
        )

        loader.load()

        checks["core_import"] = True

        fingerprint = (
            loader
            .constitution_fingerprint()
        )

        checks["constitution"] = (
            len(fingerprint) == 64
        )

    except Exception:
        checks["core_import"] = False
        checks["constitution"] = False

    checks["ok"] = all(
        bool(value)
        for key, value in checks.items()
        if key != "ok"
    )

    return checks


