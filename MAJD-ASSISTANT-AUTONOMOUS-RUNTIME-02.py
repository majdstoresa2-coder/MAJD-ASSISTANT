class BackupManager:
    def __init__(
        self,
        db: RuntimeDatabase,
    ):
        self.db = db

    def backup(
        self,
        path: Path,
    ) -> Optional[BackupRecord]:
        if not path.exists():
            return None

        backup_id = new_id("backup")

        destination = (
            BACKUP_DIR
            / backup_id
            / relative_path(path)
        )

        destination.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        shutil.copy2(
            path,
            destination,
        )

        record = BackupRecord(
            backup_id=backup_id,
            source_path=str(path),
            backup_path=str(destination),
            sha256=sha256_file(destination),
            created_at=utc_now(),
        )

        self.db.save_backup(record)

        return record

    def restore(
        self,
        record: BackupRecord,
    ) -> bool:
        source = Path(record.backup_path)
        destination = Path(record.source_path)

        if not source.exists():
            return False

        if sha256_file(source) != record.sha256:
            return False

        destination.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        shutil.copy2(
            source,
            destination,
        )

        return (
            destination.exists()
            and sha256_file(destination)
            == record.sha256
        )


