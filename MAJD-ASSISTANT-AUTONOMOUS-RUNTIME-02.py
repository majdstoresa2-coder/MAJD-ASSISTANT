class ChangeManager:
    def __init__(
        self,
        db: RuntimeDatabase,
        backup_manager: BackupManager,
        validator: ProjectValidator,
    ):
        self.db = db
        self.backup_manager = (
            backup_manager
        )
        self.validator = validator

    def _target(
        self,
        relative: str,
    ) -> Path:
        return (
            PROJECT_ROOT / relative
        ).resolve()

    def _inside_project(
        self,
        path: Path,
    ) -> bool:
        try:
            path.relative_to(
                PROJECT_ROOT.resolve()
            )
            return True
        except ValueError:
            return False

    def apply(
        self,
        proposal: ChangeProposal,
    ) -> ValidationResult:
        allowed, reason = (
            ProtectedPathPolicy.safe_target(
                proposal.relative_path,
                allow_core_update=(
                    ALLOW_CORE_UPDATES
                ),
            )
        )

        if not allowed:
            self.db.event(
                "CHANGE_BLOCKED",
                Risk.HIGH,
                {
                    "proposal": (
                        proposal.proposal_id
                    ),
                    "path": (
                        proposal.relative_path
                    ),
                    "reason": reason,
                },
            )

            return ValidationResult(
                success=False,
                errors=[reason],
            )

        target = self._target(
            proposal.relative_path
        )

        if not self._inside_project(
            target
        ):
            return ValidationResult(
                success=False,
                errors=[
                    "TARGET_OUTSIDE_PROJECT"
                ],
            )

        if (
            proposal.change_type
            in {
                ChangeType.CREATE,
                ChangeType.UPDATE,
            }
            and proposal.content is None
        ):
            return ValidationResult(
                success=False,
                errors=[
                    "MISSING_CONTENT"
                ],
            )

        content = proposal.content or ""

        if target.suffix == ".py":
            source_validation = (
                SourceValidator
                .validate_python_source(
                    content
                )
            )

            if not source_validation.success:
                return source_validation

        elif SecretGuard.contains_secret(
            content
        ):
            return ValidationResult(
                success=False,
                errors=[
                    "POSSIBLE_SECRET_IN_SOURCE"
                ],
            )

        backup = (
            self.backup_manager.backup(
                target
            )
        )

        existed_before = target.exists()

        try:
            if proposal.change_type in {
                ChangeType.CREATE,
                ChangeType.UPDATE,
            }:
                atomic_write_text(
                    target,
                    content,
                )

            elif (
                proposal.change_type
                == ChangeType.DELETE
            ):
                if target.exists():
                    target.unlink()

            validation = (
                self.validator.full_validation()
            )

            if validation.success:
                self.db.record_generated_file(
                    target,
                    proposal.source,
                    "ACTIVE",
                    {
                        "proposal_id": (
                            proposal.proposal_id
                        ),
                        "reason": proposal.reason,
                    },
                )

                self.db.event(
                    "CHANGE_ACTIVATED",
                    Risk.MEDIUM,
                    {
                        "proposal": (
                            proposal.proposal_id
                        ),
                        "path": (
                            proposal.relative_path
                        ),
                        "source": (
                            proposal.source
                        ),
                    },
                )

                return validation

            # Automatic rollback.
            if backup is not None:
                restored = (
                    self.backup_manager.restore(
                        backup
                    )
                )
            elif not existed_before:
                with contextlib.suppress(
                    FileNotFoundError
                ):
                    target.unlink()

                restored = not target.exists()
            else:
                restored = False

            self.db.event(
                "CHANGE_ROLLBACK",
                Risk.HIGH,
                {
                    "proposal": (
                        proposal.proposal_id
                    ),
                    "path": (
                        proposal.relative_path
                    ),
                    "restored": restored,
                    "errors": (
                        validation.errors
                    ),
                },
            )

            validation.errors.append(
                "ROLLED_BACK"
                if restored
                else "ROLLBACK_FAILED"
            )

            return validation

        except Exception as exc:
            restored = False

            if backup is not None:
                restored = (
                    self.backup_manager.restore(
                        backup
                    )
                )
            elif not existed_before:
                with contextlib.suppress(
                    FileNotFoundError
                ):
                    target.unlink()
                restored = True

            return ValidationResult(
                success=False,
                errors=[
                    f"{type(exc).__name__}: "
                    f"{exc}",
                    (
                        "ROLLED_BACK"
                        if restored
                        else "ROLLBACK_FAILED"
                    ),
                ],
            )


