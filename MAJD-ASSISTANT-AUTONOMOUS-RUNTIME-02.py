class GitManager:
    def __init__(
        self,
        runner: CommandRunner,
        db: RuntimeDatabase,
    ):
        self.runner = runner
        self.db = db

    def available(self) -> bool:
        return (
            shutil.which("git")
            is not None
            and (
                PROJECT_ROOT / ".git"
            ).exists()
        )

    def status(self) -> CommandResult:
        if not self.available():
            return CommandResult(
                success=False,
                argv=[],
                returncode=None,
                stderr="GIT_NOT_AVAILABLE",
            )

        return self.runner.run(
            [
                "git",
                "status",
                "--porcelain",
            ],
            cwd=PROJECT_ROOT,
        )

    def commit_generated_changes(
        self,
        message: str,
    ) -> CommandResult:
        if not AUTO_GIT_COMMIT:
            return CommandResult(
                success=False,
                argv=[],
                returncode=None,
                stderr=(
                    "AUTO_GIT_COMMIT_DISABLED"
                ),
            )

        if not self.available():
            return CommandResult(
                success=False,
                argv=[],
                returncode=None,
                stderr="GIT_NOT_AVAILABLE",
            )

        # Only generated/runtime-owned paths.
        add_result = self.runner.run(
            [
                "git",
                "add",
                "--",
                "majd_generated",
                "tests",
                "requirements.txt",
            ],
            cwd=PROJECT_ROOT,
        )

        if not add_result.success:
            return add_result

        result = self.runner.run(
            [
                "git",
                "commit",
                "-m",
                message,
            ],
            cwd=PROJECT_ROOT,
        )

        self.db.event(
            "GIT_COMMIT",
            (
                Risk.MEDIUM
                if result.success
                else Risk.HIGH
            ),
            {
                "success": result.success,
                "returncode": (
                    result.returncode
                ),
            },
        )

        return result


